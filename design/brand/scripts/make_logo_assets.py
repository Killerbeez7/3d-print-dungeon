"""Production wordmark: "3D PRINT" (Geist Mono) over DUNGEON (Chakra Petch Bold).
Writes src/features/shared/components/brandPaths.ts.

The letters are outlined straight from the fonts (kerned with HarfBuzz, overlaps removed), so the
site needs neither font for the logo. Chakra Petch's cut corners echo the chamfered buttons.
The "3D PRINT" line is about a third of the cap height so it still reads when the logo is small
(26 px tall in the phone menu)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.ttLib.removeOverlaps import removeOverlaps
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path
from fontword import word, contours, MONO, path_bbox, fmt

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
DISPLAY = os.path.join(HERE, "..", "fonts", "ChakraPetch-Bold.ttf")  # SIL OFL 1.1, see fonts/

CAP = 75          # DUNGEON cap height (units of the SVG)
LABEL_CAP = 26    # "3D PRINT" cap height
LABEL_GAP = 11    # from the top of DUNGEON to the baseline of "3D PRINT"
LABEL_TRACKING = 110  # extra advance per letter, Geist Mono units (1000 per em)


def transform(d, dx, dy, s):
    pen = SVGPathPen(None, ntos=fmt)
    parse_path(d, TransformPen(pen, (s, 0, 0, s, dx, dy)))
    return pen.getCommands()


# --- DUNGEON: Chakra Petch Bold, baseline at y=0, caps exactly CAP tall
tt = TTFont(DISPLAY)
removeOverlaps(tt)
face = hb.Face(open(DISPLAY, "rb").read())
buf = hb.Buffer()
buf.add_str("DUNGEON")
buf.guess_segment_properties()
hb.shape(hb.Font(face), buf, {})
order = tt.getGlyphOrder()
glyphs, x = [], 0
for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
    glyphs.append((order[info.codepoint], x + pos.x_offset))
    x += pos.x_advance
s = CAP / tt["glyf"]["D"].yMax  # flat-topped D = cap height
letters = "".join("".join(contours(tt, g, gx, s)) for g, gx in glyphs)
wb = path_bbox(letters)  # (xmin, ymin, xmax, ymax), y down

# --- label: Geist Mono 500, left edge on DUNGEON's left edge
lab = word("3D PRINT", 500, src=MONO, tracking=LABEL_TRACKING)
ls = LABEL_CAP / lab["cap"]
lb = path_bbox(lab["d"])
label = transform(lab["d"], wb[0] - lb[0] * ls, -CAP - LABEL_GAP, ls)
labb = path_bbox(label)

top = -(CAP + LABEL_GAP + LABEL_CAP)
bottom = max(0.0, round(wb[3] + 0.5))  # room for anything under the baseline
left, right = min(wb[0], labb[0]), max(wb[2], labb[2])
width, height = right - left, bottom - top
VB = f"{fmt(left)} {top} {fmt(width)} {fmt(height)}"

ts = f'''// Generated by design/brand/scripts/make_logo_assets.py: "3D PRINT" + DUNGEON (the wordmark beside the die).
// DUNGEON is outlined from Chakra Petch Bold, "3D PRINT" from Geist Mono. Do not edit by hand.
export const WORDMARK_VIEWBOX = "{VB}";
export const LABEL_PATH = "{label}";
export const LETTERS_PATH = "{letters}";
/** Width / height of the wordmark SVG, for sizing without layout shift. */
export const WORDMARK_RATIO = {round(width / height, 4)};
'''
open(os.path.join(REPO, "src/features/shared/components/brandPaths.ts"), "w").write(ts)
print("viewBox", VB, "ratio", round(width / height, 4), "label width", round(labb[2] - labb[0], 1),
      "dungeon width", round(wb[2] - wb[0], 1), "bytes", len(ts))
